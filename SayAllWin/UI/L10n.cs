    public static AppLanguage Language { get; private set; } = AppLanguage.System;

    public static void SetLanguage(AppLanguage language)
    {
        Language = language;
        CultureInfo.CurrentUICulture = ResolveCulture();
        Culture = ResolveCulture();
    }

    public static CultureInfo Culture { get; private set; } = CultureInfo.GetCultureInfo("en-US");

    private static CultureInfo ResolveCulture()
    {
        return Language switch
        {
            AppLanguage.zh_Hans => CultureInfo.GetCultureInfo("zh-CN"),
            AppLanguage.en => CultureInfo.GetCultureInfo("en-US"),
            _ => CultureInfo.CurrentUICulture,
        };
    }

    public static string T(string key, params object[] args)
    {
        var table = Language is AppLanguage.en ? En
            : Language is AppLanguage.zh_Hans ? Zh
            : CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "zh" ? Zh : En;
        if (!table.TryGetValue(key, out var value))
        {
            value = En.TryGetValue(key, out var en) ? en : key;
        }
        return args.Length > 0 ? string.Format(Culture, value, args) : value;
    }

    public static bool IsZh => (Language is AppLanguage.zh_Hans)
        || (Language is AppLanguage.System && CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "zh");
